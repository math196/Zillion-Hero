export function translate(language, key, variables = {}) {
  const template = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.pt[key] ?? key;
  return Object.entries(variables).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function translateStatic(language, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(language, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(language, element.dataset.i18nAriaLabel));
  });
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  document.title = translate(language, "meta.title");
  document.querySelector('meta[name="description"]')?.setAttribute("content", translate(language, "meta.description"));
}

